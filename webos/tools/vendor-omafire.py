#!/usr/bin/env python3
"""Vendor Wes Grimes' OmaFire campfire engine into the shared webOS/Tizen app.

Usage: python3 webos/tools/vendor-omafire.py /path/to/omafire

OmaFire (https://github.com/wesleygrimes/omafire, MIT) is a Quickshell bar plugin. Its QML only hosts the
popup; the simulation and the 360 x 240 software renderer live in ui/fire/fire.js, plain JavaScript with
no QML or DOM dependencies. This script writes:

  webos/app/vendor/omafire/fire.js   ui/fire/fire.js unchanged apart from the QML-only ".pragma library"
                                     line, wrapped in a function scope that exposes its own module.exports
                                     block as window.OmaFire (and as module.exports under node).
  webos/app/vendor/omafire/art.js    assets/campsite-approved.webp (720 x 480) sampled to 360 x 240 exactly
                                     like fire.js prepareBackground() (nearest, even source pixels), as
                                     base64 RGB in window.OmaFireArt. Pre-decoding it means the TV never
                                     reads pixels back from a canvas (no file:// taint, no WebP decoder).
  webos/app/vendor/omafire/crackle.wav  assets/crackle.wav unchanged.

His MIT licence is kept in each generated header. Needs Pillow with WebP support.
"""
import base64
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

src = Path(sys.argv[1]).resolve()
out = Path(__file__).resolve().parent.parent / "app/vendor/omafire"
commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
version = __import__("json").loads((src / "manifest.json").read_text(encoding="utf-8"))["version"]
lic = (src / "LICENSE").read_text(encoding="utf-8").strip()
lic_block = "\n".join(" * " + l if l else " *" for l in lic.splitlines())


def header(what):
    return ("/*\n * " + what + ", vendored from Wes Grimes' OmaFire\n"
            " * https://github.com/wesleygrimes/omafire (v" + version + ", commit " + commit + ")\n"
            " * Generated by webos/tools/vendor-omafire.py; do not edit by hand.\n *\n" + lic_block + "\n */\n")


out.mkdir(parents=True, exist_ok=True)

body = (src / "ui/fire/fire.js").read_text(encoding="utf-8")
body = "\n".join(l for l in body.splitlines() if l.strip() != ".pragma library")
fire = (header("ui/fire/fire.js (unchanged apart from the QML \".pragma library\" line)")
        + "(function (root) {\nvar module = { exports: {} };\n" + body
        + "\nroot.OmaFire = module.exports;\n"
        + "if (typeof window === \"undefined\" && typeof exports !== \"undefined\") exports.OmaFire = module.exports;\n"
        + "})(typeof window !== \"undefined\" ? window : this);\n")
(out / "fire.js").write_text(fire, encoding="utf-8")

img = Image.open(src / "assets/campsite-approved.webp").convert("RGB")
assert img.size == (720, 480), img.size
px = img.load()
# fire.js nearestIndex(i, 720, 360) == 2 * i: the reference samples even source pixels.
rgb = bytearray()
for y in range(240):
    for x in range(360):
        rgb += bytes(px[2 * x, 2 * y])
art = (header("assets/campsite-approved.webp, sampled to 360 x 240 RGB")
       + "(function (root) {\n  root.OmaFireArt = { w: 360, h: 240, rgb: \""
       + base64.b64encode(bytes(rgb)).decode() + "\" };\n"
       + "})(typeof window !== \"undefined\" ? window : this);\n")
(out / "art.js").write_text(art, encoding="utf-8")

shutil.copyfile(src / "assets/crackle.wav", out / "crackle.wav")
for f in sorted(out.iterdir()):
    print(f, f.stat().st_size)
